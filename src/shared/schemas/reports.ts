import * as z from 'zod'

import {
  MAX_DESCRIPTION_LENGTH,
  MAX_PHOTO_BYTES,
  MAX_PHOTOS,
  PHOTO_FORMATS,
  textLength,
} from '../domain/limits'
import { id } from './common'

// Input of the registration endpoints (SDD 7.2, Reportes y duplicados, and 8.2). Whether the
// chosen campus, building, space and category are offered (RF-REPORTE-13) is checked by the
// service against the catalog; these schemas only check the shape.

// RF-REPORTE-01, 02 (SDD 10.8): not empty once trimmed and at most 1,000 characters, counted as
// code points. It is stored trimmed.
export const description = z
  .string({ error: 'La descripción es obligatoria.' })
  .trim()
  .refine((text) => text.length > 0, {
    error: 'La descripción no puede quedar vacía.',
    params: { code: 'DESCRIPTION_REQUIRED' },
  })
  .refine((text) => textLength(text) <= MAX_DESCRIPTION_LENGTH, {
    error: 'La descripción no puede exceder 1,000 caracteres.',
    params: { code: 'DESCRIPTION_TOO_LONG' },
  })

// RF-REPORTE-01: campus, building, space and category are required.
const selection = {
  campusId: id,
  buildingId: id,
  spaceId: id,
  categoryId: id,
}

// POST /api/reports/check: validates the draft before any photo is uploaded (SDD 8.2).
export const checkReportBody = z.strictObject({
  ...selection,
  description,
  photoCount: z
    .int({ error: 'El número de fotografías debe ser un entero.' })
    .min(0, { error: 'El número de fotografías no puede ser negativo.' })
    .max(MAX_PHOTOS, { error: `Un reporte acepta hasta ${MAX_PHOTOS} fotografías.` }),
})

// A photo as Cloudinary describes it after the signed upload. The service checks the signature
// before registering the report (SDD 10.10).
export const uploadedPhoto = z.strictObject({
  publicId: z.string().min(1),
  version: z.int().positive(),
  signature: z.string().min(1),
  // RF-REPORTE-09
  format: z.enum(PHOTO_FORMATS, {
    error: 'La fotografía debe estar en formato JPEG, PNG, WebP o HEIC.',
  }),
  // RF-REPORTE-04
  bytes: z
    .int()
    .positive()
    .max(MAX_PHOTO_BYTES, { error: 'Cada fotografía puede pesar hasta 10 MB.' }),
})

// POST /api/reports. The id is generated by the client so that sending twice does not create
// two reports (SDD 6.2). `reviewedDuplicateIds` lists the possible duplicates the account
// already saw and set aside (SDD 8.2).
export const createReportBody = z.strictObject({
  id,
  ...selection,
  description,
  // RF-REPORTE-03
  photos: z
    .array(uploadedPhoto)
    .max(MAX_PHOTOS, { error: `Un reporte acepta hasta ${MAX_PHOTOS} fotografías.` })
    .refine((photos) => new Set(photos.map((photo) => photo.publicId)).size === photos.length, {
      error: 'La misma fotografía se adjuntó más de una vez.',
    }),
  reviewedDuplicateIds: z.array(id),
})

export type CheckReportBody = z.infer<typeof checkReportBody>
export type UploadedPhoto = z.infer<typeof uploadedPhoto>
export type CreateReportBody = z.infer<typeof createReportBody>
